CY_CLEAR = f"MATCH (n:{LABEL}) DETACH DELETE n"
CY_INDEX = f"CREATE INDEX ON :{LABEL}(name)"


def _persons_rows() -> list[dict]:
    return [
        {"name": n, "faction": f, "title": t} for (n, f, t) in PERSONS
    ]


def _relations_rows() -> list[dict]:
    return [
        {"a": a, "p": p, "b": b} for (a, p, b) in RELATIONS
    ]


def _drop_index(session) -> None:
    try:
        session.run(f"DROP INDEX ON :{LABEL}(name)")
    except Exception:
        pass


def build_graph(driver) -> tuple[int, int]:
    with driver.session() as s:
        s.run(CY_CLEAR)
        _drop_index(s)
        s.run(CY_INDEX)
        s.run(
            f"UNWIND $rows AS r "
            f"CREATE (:{LABEL} {{name: r.name, faction: r.faction, title: r.title}})",
            rows=_persons_rows(),
        )
        s.run(
            f"UNWIND $rows AS r "
            f"MATCH (a:{LABEL} {{name: r.a}}), (b:{LABEL} {{name: r.b}}) "
            f"CREATE (a)-[:REL {{type: r.p}}]->(b)",
            rows=_relations_rows(),
        )
        n = s.run(f"MATCH (x:{LABEL}) RETURN count(x) AS c").single()["c"]
        m = s.run(
            f"MATCH (:{LABEL})-[r:REL]->(:{LABEL}) RETURN count(r) AS c"
        ).single()["c"]
        return n, m


def _missing_endpoints() -> list[str]:
    names = {n for (n, _, _) in PERSONS}
    bad: list[str] = []
    for a, p, b in RELATIONS:
        if a not in names:
            bad.append(f"{a} (in '{a}-{p}->{b}')")
        if b not in names:
            bad.append(f"{b} (in '{a}-{p}->{b}')")
    return bad


VIEW_QUERIES = f"""
// === 全图（节点 + 所有关系） ===
MATCH (n:{LABEL})-[r:REL]->(m:{LABEL}) RETURN n, r, m;

// === 仅蜀汉阵营 ===
MATCH (n:{LABEL} {{faction: '蜀'}})-[r:REL]->(m:{LABEL} {{faction: '蜀'}})
RETURN n, r, m;

// === 桃园三结义 + 关张子嗣 ===
MATCH p = (n:{LABEL})-[:REL*1..2]-(m:{LABEL})
WHERE n.name IN ['刘备','关羽','张飞']
RETURN p;

// === 诸葛亮的全部关系（出 + 入） ===
MATCH (n:{LABEL} {{name: '诸葛亮'}})-[r:REL]-(m:{LABEL})
RETURN n, r, m;

// === 按关系类型过滤：所有「结义」 ===
MATCH (n:{LABEL})-[r:REL {{type: '结义'}}]->(m:{LABEL}) RETURN n, r, m;

// === 三大主公及其麾下（君臣两跳） ===
MATCH p = (lord:{LABEL})<-[:REL {{type: '君臣'}}]-(s:{LABEL})
WHERE lord.name IN ['刘备','曹操','孙权']
RETURN p;
""".strip()


def main() -> int:
    bad = _missing_endpoints()
    if bad:
        print("[error] relations reference unknown persons:", file=sys.stderr)
        for b in bad[:20]:
            print(f"  - {b}", file=sys.stderr)
        return 2
    drv = GraphDatabase.driver(URI, auth=(USER, PASS))
    try:
        drv.verify_connectivity()
        n, m = build_graph(drv)
    finally:
        drv.close()
    print(f"[ok] loaded {n} persons, {m} relations into Memgraph at {URI}")
    print()
    print("# Memgraph Lab queries (paste into Lab → Query Execution):")
    print(VIEW_QUERIES)
    return 0


if __name__ == "__main__":
    sys.exit(main())
